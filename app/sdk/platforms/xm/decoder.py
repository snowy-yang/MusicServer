#: PC 桌面端 playUrlList 的 AES-ECB 密钥（客户端 4.0.14 asar Gt 函数提取）
WIN_AES_KEY = bytes.fromhex("aaad3e4fd540b0f79dca95606e72bf93")


def _b64url_to_buf(text: str) -> bytes:
    cleaned = text.replace("_", "/").replace("-", "+")
    cleaned += "=" * (-len(cleaned) % 4)
    return base64.b64decode(cleaned)


def decode_www2_url(encrypted: str) -> str:
    """www2/mweb2 加密 URL → 明文 URL。"""
    if not encrypted:
        return ""
    if encrypted.startswith("http"):
        return encrypted
    decoded = _b64url_to_buf(encrypted)
    if len(decoded) < 16:
        raise RuntimeError("密文长度不足（缺少 IV）")
    body = bytearray(decoded[:-16])
    iv = decoded[-16:]

    for i in range(len(body)):
        body[i] = PERMUTATION_TABLE_O[body[i]]
    for i in range(0, len(body), 16):
        count = min(16, len(body) - i)
        for j in range(count):
            body[i + j] ^= iv[j]
    for i in range(0, len(body), 32):
        count = min(32, len(body) - i)
        for j in range(count):
            body[i + j] ^= XOR_KEY_A[j]
    return bytes(body).decode("utf-8", errors="replace")


def decode_win_url(encrypted: str) -> str:
    """PC 桌面端（device=win）AES-ECB 加密 URL → 明文 URL（解出的是带签名付费地址）。"""
    if not encrypted:
        return ""
    if encrypted.startswith("http"):
        return encrypted
    decryptor = Cipher(algorithms.AES(WIN_AES_KEY), modes.ECB()).decryptor()
    plain = decryptor.update(_b64url_to_buf(encrypted)) + decryptor.finalize()
    return pkcs7_unpad(plain).decode("utf-8", errors="replace")
